#Was für Variablen gibt es in Python und wie werden sie verwendet?
#1. Numerische Variablen: Diese Variablen speichern Zahlenwerte, wie Ganzzahlen (int) und Gleitkommazahlen (float).
#Beispiel:
a= type(int) #int = Ganzzahl
b= type(float) #float = Gleitkommazahl
a = 10        # Ganzzahl
b = 3.14      # Gleitkommazahl

#2. Zeichenkettenvariablen: Diese Variablen speichern Textwerte und werden durch Anführungszeichen definiert.
#Beispiel:
c= type(str) #str = string/Zeichenkette
c = "Hallo, Welt!"  # Zeichenkette
#3. Boolesche Variablen: Diese Variablen speichern Wahrheitswerte, entweder True oder False.
#Beispiel:
d= type(bool) #bool = boolean/Wahrheitswert
d = True       # Wahrheitswert
e = False      # Wahrheitswert
#4. Listenvariablen: Diese Variablen speichern eine geordnete Sammlung von Elementen, die verschiedene Datentypen enthalten können.
#Beispiel:
f= type(list) #list = Liste
f = [1, 2, 3, "vier", 5.0]  # Liste mit verschiedenen Datentypen
#5. Tupelvariablen: Diese Variablen speichern eine geordnete, unveränderliche Sammlung von Elementen.
#Beispiel:
g= type(tuple) #tuple = Tupel
g = (1, 2, 3, "vier", 5.0)  # Tupel mit verschiedenen Datentypen
#6. Wörterbuchvariablen: Diese Variablen speichern Schlüssel-Wert-Paare, die eine Zuordnung zwischen Schlüsseln und Werten ermöglichen.
#Beispiel:
h= type(dict) #dict = dictionary/Wörterbuch
h = {"Name": "Alice", "Alter": 30, "Stadt": "Berlin"}  # Wörterbuch mit Schlüssel-Wert-Paaren
#7. Mengenvariablen: Diese Variablen speichern eine ungeordnete Sammlung von eindeutigen Elementen.
#Beispiel:
i= type(set) #set = Menge
i = {1, 2, 3, 4, 5}  # Menge mit eindeutigen Elementen
#Variablen in Python werden verwendet, um Daten zu speichern und zu manipulieren. Sie können Werte zuweisen, ändern und abrufen,
#indem Sie den Variablennamen verwenden.
# Variablen sind dynamisch typisiert, was bedeutet, dass der Datentyp einer Variablen zur Laufzeit geändert werden kann.


#Zusammenfassend gibt es in Python verschiedene Arten von Variablen, darunter numerische Variablen, Zeichenkettenvariablen,
# boolesche Variablen, Listenvariablen, Tupelvariablen, Wörterbuchvariablen und Mengenvariablen.
# Jede Art von Variable hat ihre eigenen Eigenschaften und Verwendungszwecke,
# die es ermöglichen, verschiedene Arten von Daten zu speichern und zu manipulieren.
